    private static readonly HashSet<string> Codes = new(ByName.Values, StringComparer.OrdinalIgnoreCase);

    /// <summary>Resolves a country name or two-letter code; false when it is neither.</summary>
    public static bool TryResolve(string? country, out string code)
    {
        var value = (country ?? string.Empty).Trim();
        if (ByName.TryGetValue(value, out var found))
        {
            code = found;
            return true;
        }

        if (Codes.Contains(value))
        {
            code = value.ToUpperInvariant();
            return true;
        }

        code = string.Empty;
        return false;
    }
